"use client";
import * as React from "react";
import { cn } from "@/lib/utils";

export type QRTemplate = "classic" | "minimal" | "bold";

/** Decorative, non-scannable QR-like pattern used for live design previews. */
export function PatternQR({ fg, bg, seed = "rp", className, logo }: { fg: string; bg: string; seed?: string; className?: string; logo?: string | null }) {
  const n = 25;
  const cells = React.useMemo(() => {
    let h = 2166136261;
    for (const ch of seed) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
    const out: [number, number][] = [];
    for (let y = 0; y < n; y++)
      for (let x = 0; x < n; x++) {
        const inFinder = (x < 8 && y < 8) || (x > n - 9 && y < 8) || (x < 8 && y > n - 9);
        if (inFinder) continue;
        h = Math.imul(h ^ (x * 31 + y), 2654435761) >>> 0;
        if (h % 100 < 47) out.push([x, y]);
      }
    return out;
  }, [seed]);
  const finder = (x: number, y: number) => (
    <g key={`${x}-${y}`}>
      <rect x={x} y={y} width={7} height={7} rx={1.4} fill={fg} />
      <rect x={x + 1} y={y + 1} width={5} height={5} rx={1} fill={bg} />
      <rect x={x + 2} y={y + 2} width={3} height={3} rx={0.6} fill={fg} />
    </g>
  );
  return (
    <svg viewBox={`-2 -2 ${n + 4} ${n + 4}`} className={className} role="img" aria-label="QR design preview">
      <rect x={-2} y={-2} width={n + 4} height={n + 4} fill={bg} rx={1.5} />
      {cells.map(([x, y]) => <rect key={`${x}.${y}`} x={x + 0.08} y={y + 0.08} width={0.84} height={0.84} rx={0.2} fill={fg} />)}
      {finder(0, 0)}
      {finder(n - 7, 0)}
      {finder(0, n - 7)}
      {logo && (
        <>
          <rect x={n / 2 - 3.2} y={n / 2 - 3.2} width={6.4} height={6.4} rx={1.2} fill={bg} />
          <image href={logo} x={n / 2 - 2.6} y={n / 2 - 2.6} width={5.2} height={5.2} preserveAspectRatio="xMidYMid meet" />
        </>
      )}
    </svg>
  );
}

/**
 * Mirrors the printable A6 PDF card generated by the API (apps/api/app/services/qr_render.py).
 * The card is paper, so it uses fixed print colours (ink #0b1218, muted #52616c) in both themes.
 */
export function QRCardPreview({
  template, business, location, headline, subtext, fg, bg, brand, qr, className,
}: {
  template: QRTemplate; business: string; location: string; headline?: string | null; subtext?: string | null; fg: string; bg: string; brand: string; qr: React.ReactNode; className?: string;
}) {
  const h = headline || "How was your visit?";
  const s = subtext || "Scan to share honest feedback";
  if (template === "bold") {
    return (
      <div className={cn("relative flex aspect-[105/148] w-full flex-col items-center overflow-hidden rounded-xl p-[7%] text-white shadow-lg", className)} style={{ background: brand }}>
        <p className="text-center text-[clamp(13px,4.6cqw,20px)] font-bold leading-tight tracking-tight">{h}</p>
        <p className="mt-1 text-center text-[clamp(9px,2.6cqw,12px)] text-white/80">{s}</p>
        <div className="mt-[6%] flex w-full flex-1 items-center justify-center rounded-xl p-[8%]" style={{ background: bg }}>
          <div className="aspect-square w-full max-w-[86%]">{qr}</div>
        </div>
        <p className="mt-[5%] text-center text-[clamp(8px,2.3cqw,11px)] text-white/90">{location}</p>
        <p className="text-center text-[clamp(7px,2cqw,10px)] text-white/70">Every review — positive or negative — is welcome.</p>
      </div>
    );
  }
  return (
    <div className={cn("relative flex aspect-[105/148] w-full flex-col items-center overflow-hidden rounded-xl bg-white p-[7%] text-[#0b1218] shadow-lg", template === "classic" && "ring-1 ring-[#dde5e9]", className)}>
      <div className="absolute inset-x-0 top-0 h-1.5" style={{ background: brand }} />
      {template === "classic" && <p className="mt-1 text-center text-[clamp(9px,2.6cqw,12px)] font-bold">{business}</p>}
      <p className={cn("text-center font-bold leading-tight tracking-tight", template === "minimal" ? "mt-2 text-[clamp(14px,5cqw,22px)]" : "mt-1 text-[clamp(13px,4.6cqw,20px)]")}>{h}</p>
      <p className="mt-1 text-center text-[clamp(9px,2.6cqw,12px)] text-[#52616c]">{s}</p>
      <div className="mt-[6%] flex w-full flex-1 items-center justify-center">
        <div className="aspect-square w-full max-w-[78%] overflow-hidden rounded-lg" style={{ background: bg }}>{qr}</div>
      </div>
      <p className="mt-[5%] text-center text-[clamp(8px,2.3cqw,11px)] text-[#52616c]">{location}</p>
      <p className="text-center text-[clamp(7px,2cqw,10px)] text-[#7d8b95]">Every review — positive or negative — is welcome.</p>
    </div>
  );
}
