export function CopyButton({ text, label = "Copy" }: { text: string; label?: string }) {
  const [done, setDone] = React.useState(false);
  return (
    <Button
      variant="outline"
      size="sm"
      onClick={async () => {
        try {
          await navigator.clipboard.writeText(text);
          setDone(true);
          setTimeout(() => setDone(false), 1500);
        } catch {
          toast.error("Couldn't copy to clipboard");
        }
      }}
    >
      {done ? <Check /> : <Copy />} {done ? "Copied" : label}
    </Button>
  );
}

const SENT: Record<string, string> = { positive: "success", negative: "danger", neutral: "neutral", mixed: "warning" };
export function SentimentBadge({ value }: { value?: string | null }) {
  if (!value) return null;
  return <Badge variant={(SENT[value] as "success") ?? "neutral"} dot>{value[0].toUpperCase() + value.slice(1)}</Badge>;
}

export function ProviderNote({ provider }: { provider?: string }) {
  if (!provider) return null;
  return (
    <span className={cn("inline-flex items-center gap-1.5 rounded-full px-2 py-0.5 text-[11px] font-medium", provider === "openai" ? "bg-success-soft text-success-foreground" : "bg-muted text-muted-foreground")}>
      <span className="size-1.5 rounded-full bg-current" />
      {provider === "openai" ? "Generated by OpenAI" : "Offline heuristic engine"}
    </span>
  );
}

export function Segmented<T extends string>({ value, onChange, options, label }: { value: T; onChange: (v: T) => void; options: { value: T; label: string }[]; label: string }) {
  return (
    <div role="radiogroup" aria-label={label} className="flex flex-wrap gap-1.5">
      {options.map((o) => (
        <button
          key={o.value}
          role="radio"
          aria-checked={value === o.value}
          onClick={() => onChange(o.value)}
          className={cn(
            "h-8 rounded-lg border px-3 text-[12.5px] font-medium transition",
            value === o.value ? "border-primary bg-primary-soft text-primary-soft-foreground" : "border-border bg-card text-muted-foreground hover:border-border-strong hover:text-foreground",
          )}
        >
          {o.label}
        </button>
      ))}
    </div>
  );
}

export function RatingPicker({ value, onChange }: { value: number; onChange: (v: number) => void }) {
  return (
    <div role="radiogroup" aria-label="Rating" className="flex gap-1">
      {[1, 2, 3, 4, 5].map((n) => (
        <button
          key={n}
          role="radio"
          aria-checked={value === n}
          onClick={() => onChange(n)}
          className={cn("flex h-8 w-10 items-center justify-center gap-0.5 rounded-lg border text-[12.5px] font-semibold tabular transition", value === n ? "border-[#f5a524] bg-[#f5a524]/12 text-[#b7791f] dark:text-[#f5c26b]" : "border-border bg-card text-muted-foreground hover:border-border-strong")}
        >
          {n}★
        </button>
      ))}
    </div>
  );
}
